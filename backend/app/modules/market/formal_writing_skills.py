#: 供测试与调用方按 code 取规格
_SPEC_BY_CODE: dict[str, dict[str, Any]] = {str(spec["code"]): spec for spec in _SPECS}


def _definition(spec: dict[str, Any]) -> dict[str, Any]:
    """把技能规格转成 ``definition_json``（既有链路字段 + SkillSpec 契约字段）。"""
    risk = str(spec["risk"])
    steps = [
        {"kind": "prompt", "title": title, "text": text}
        for title, text in zip(_STEP_TITLES, spec["steps"], strict=False)
    ]
    return {
        # ---- 既有链路字段 ----
        "name": spec["name"],
        "description": spec["description"],
        "prompt": spec["prompt"],
        "steps": steps,
        "source_url": None,
        "license": LICENSE,
        "author": AUTHOR,
        "category": "office",
        "skill_group": spec["group"],
        #: 推荐 Word 版式（docs/render_docx.py 的 doc_style 取值）
        "doc_style": spec["doc_style"],
        "tags": list(spec["tags"]),
        # ---- SkillSpec 契约字段 ----
        "code": spec["code"],
        "version": "1.0.0",
        "summary": spec["description"],
        "when_to_use": spec["when_to_use"],
        "inputs": [
            {"key": key, "label": label, "required": required, "type": kind}
            for key, label, required, kind in spec["inputs"]
        ],
        "allowed_tools": ["knowledge.search"],
        "knowledge_scopes": ["yard"],
        "eval_cases": [
            {"input": case_input, "expect": expect} for case_input, expect in spec["eval_cases"]
        ],
        "guardrails": {
            "risk_level": risk,
            "max_steps": len(steps),
            "require_citation": False,
        },
        "output_format": "markdown",
        "sources": [],
    }


#: SkillSpec 认识的字段（definition 还带上架/分组等平台字段，校验时按此投影）
