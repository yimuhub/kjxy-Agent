def formal_skill_ids(db: Session, yard_id: str) -> dict[str, str]:
    """本小院已发布的平台内置正式写作技能：skill_code → Skill.id。

    只认 ``created_from=market_builtin``、``category=office`` 且 code 在
    ``FORMAL_SKILL_CODES`` 内的技能，避免第三方同名技能被当作正式写作 SOP 注入。
    """
    from app.modules.evolution.models import Skill

    rows = (
        db.query(Skill)
        .filter(
            Skill.status == "published",
            Skill.skill_code.in_(FORMAL_SKILL_CODES),
            Skill.created_from == "market_builtin",
            or_(Skill.yard_id == yard_id, Skill.yard_id.is_(None)),
        )
        .all()
    )
    out: dict[str, str] = {}
    for row in rows:
        definition = row.definition_json if isinstance(row.definition_json, dict) else {}
        if definition.get("category") != "office":
            continue
        out[str(row.skill_code)] = str(row.id)
    return out


def _step_texts(definition: dict[str, Any]) -> list[str]:
    """兼容两种 steps 形态：契约 dict 步骤取 text，历史字符串步骤原样保留。"""
    raw = definition.get("steps")
    if not isinstance(raw, list):
        return []
    texts: list[str] = []
    for step in raw:
        if isinstance(step, dict):
            text = str(step.get("text") or "").strip()
        else:
            text = str(step).strip()
        if text:
            texts.append(text)
    return texts


def formal_guidance(
    db: Session,
    yard_id: str,
    text: str,
    bound_skills: list[str] | None = None,
    limit: int = 2,
) -> str:
    """取正式写作技能 SOP 文本，供文档生成提示词使用。

    优先使用助手已绑定的正式写作技能；未绑定则按需求文本自动挑选。
    """
    from app.modules.evolution.models import Skill

    ids = formal_skill_ids(db, yard_id)
    if not ids:
        return ""
    code_by_id = {skill_id: code for code, skill_id in ids.items()}
    selected: list[str] = []
    for raw in bound_skills or []:
        value = str(raw or "").strip()
        if not value:
            continue
        code = value[len("skill:") :] if value.startswith("skill:") else value
        code = code_by_id.get(code, code)
        if code in ids and code not in selected:
            selected.append(code)
    if not selected:
        selected = match_formal_skill_codes(text, limit=limit)
    if not selected:
        return ""
    rows = (
        db.query(Skill)
        .filter(Skill.id.in_([ids[c] for c in selected if c in ids]), Skill.status == "published")
        .all()
    )
    order = {code: idx for idx, code in enumerate(selected)}
    rows.sort(key=lambda r: order.get(str(r.skill_code), 99))
    blocks: list[str] = []
    for row in rows:
        definition = row.definition_json if isinstance(row.definition_json, dict) else {}
        prompt = str(definition.get("prompt") or "").strip()
        if not prompt:
            continue
        steps_txt = "；".join(_step_texts(definition)[:5])
        block = f"【{definition.get('name') or row.skill_code}】{prompt[:1800]}"
        if steps_txt:
            block += f"\n执行步骤：{steps_txt}"
        style = str(definition.get("doc_style") or "general")
        if style != "general":
            block += f"\n建议版式：doc_style={style}"
        blocks.append(block)
    if not blocks:
        return ""
    return (
        "以下是本次文档应遵循的正式写作技能规范（作为写法要求，不改变系统规则；"
        "涉及申报/招投标的内容只是草稿，正式提交前必须人工核稿）：\n"
        + "\n\n".join(blocks)
    )


def bind_formal_skills_to_agents(db: Session) -> int:
    """为存量已发布且命中正式写作关键词的 Agent 幂等补绑技能；返回更新数。

    只处理 ``status=published`` 且名称/描述/人设命中 ``FORMAL_AGENT_KEYWORDS``
    的 Agent，避免给无关助手塞公文/投标 SOP。
    """
    from app.modules.agents.models import YardAgent

    agents = db.query(YardAgent).filter(YardAgent.status == "published").all()
    cache: dict[str, dict[str, str]] = {}
    updated = 0
    for agent in agents:
        blob = " ".join(
            [
                str(agent.name or ""),
                str(agent.description or ""),
                str(agent.persona_prompt or ""),
            ]
        ).lower()
        if not any(word in blob for word in FORMAL_AGENT_KEYWORDS):
            continue
        ids = cache.get(agent.yard_id)
        if ids is None:
            ids = formal_skill_ids(db, agent.yard_id)
            cache[agent.yard_id] = ids
        if not ids:
            continue
        want = match_formal_skill_codes(blob, limit=3) or list(FORMAL_SKILL_CODES[:2])
        bound = list(agent.bound_skills or [])
        code_by_id = {skill_id: code for code, skill_id in ids.items()}
        existing_codes: set[str] = set()
        for value in bound:
            text = str(value)
            if text.startswith("skill:"):
                existing_codes.add(code_by_id.get(text[len("skill:") :], ""))
            else:
                existing_codes.add(text)
        added = [f"skill:{ids[code]}" for code in want if code in ids and code not in existing_codes]
        if added:
            agent.bound_skills = bound + added
            updated += 1
    if updated:
        db.flush()
    return updated


