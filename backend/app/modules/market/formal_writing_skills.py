def _prompt(
    *,
    role: str,
    structure: str,
    tone: str,
    risk: str = "low",
    extra_rule: str = "",
) -> str:
    """拼装技能提示词：角色 + 结构 + 语气 + 事实纪律 + 输出清单。"""
    parts = [
        f"你是{role}。",
        f"写作结构：{structure}",
        f"语气与格式：{tone}",
        _FACT_RULES,
        _NO_FABRICATION_RULE,
    ]
    if risk == "medium":
        parts.append(_SUBMIT_RULE)
    if extra_rule:
        parts.append(extra_rule)
    parts.append(_OUTPUT_TAIL)
    return "\n".join(parts)


def _spec(
    *,
    code: str,
    group: str,
    name: str,
    description: str,
    role: str,
    structure: str,
    tone: str,
    when_to_use: str,
    steps: tuple[str, ...],
    tags: tuple[str, ...],
    eval_cases: tuple[tuple[str, str], ...],
    inputs: tuple[tuple[str, str, bool, str], ...] = (),
    risk: str = "low",
    extra_rule: str = "",
) -> dict[str, Any]:
    """技能原始规格（纯数据；落库前由 ``_definition`` 转成契约形态）。"""
    return {
        "code": code,
        "group": group,
        "name": name,
        "description": description,
        "when_to_use": when_to_use,
        "prompt": _prompt(role=role, structure=structure, tone=tone, risk=risk, extra_rule=extra_rule),
        "steps": steps,
        "tags": tags,
        "inputs": inputs,
        "eval_cases": eval_cases,
        "risk": risk,
        "doc_style": _DOC_STYLE_BY_CODE[code],
    }


