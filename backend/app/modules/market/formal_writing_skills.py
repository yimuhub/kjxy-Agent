def spec_payload(definition: dict[str, Any]) -> dict[str, Any]:
    """从 definition 投影出 SkillSpec 可校验的字段（丢掉上架/分组等平台字段）。"""
    return {key: definition[key] for key in SPEC_FIELDS if key in definition}


def select_formal_skill_codes(text: str, limit: int = 2) -> list[str]:
    """按文本挑选最相关的正式写作技能（无命中返回空列表）。"""
    return match_formal_skill_codes(text, limit=limit)


def match_formal_skill_codes(text: str, limit: int = 3) -> list[str]:
    """按关键词命中打分挑选技能（长词权重更高，同分按 code 稳定排序）。"""
    lowered = f" {(text or '').lower()} "
    if not lowered.strip():
        return []
    scored: list[tuple[int, str]] = []
    for code, words in _SKILL_KEYWORDS.items():
        score = sum(len(word) for word in words if word in lowered)
        if score:
            scored.append((score, code))
    scored.sort(key=lambda item: (-item[0], item[1]))
    return [code for _, code in scored[:limit]]


def need_keywords(code: str) -> list[str]:
    """技能匹配用关键词（给一句话生成的 skill_needs 使用）。"""
    return list(_SKILL_KEYWORDS.get(code, ()))


def is_formal_request(text: str) -> bool:
    """是否属于公文/申报/招投标/正式写作请求。"""
    lowered = (text or "").lower()
    return any(word in lowered for word in FORMAL_AGENT_KEYWORDS)


def doc_style_for_code(code: str) -> str:
    """技能对应的 Word 版式（未知 code 回落 general）。"""
    return _DOC_STYLE_BY_CODE.get(code, "general")


